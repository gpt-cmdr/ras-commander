"""The native wheel ships its own, the engine's and every linked crate's licence."""
from pathlib import Path
import tomllib

ROOT = Path(__file__).resolve().parents[2]
FAST_HDF = ROOT / "rust/fast-hdf"


def test_wheel_license_files_cover_the_notice_bundle():
    project = tomllib.loads((FAST_HDF / "pyproject.toml").read_text())["project"]
    assert project["license"] == "MIT"
    assert "THIRD-PARTY-NOTICES.md" in project["license-files"]
    assert "licenses/*" in project["license-files"]
    for name in ("ras-commander-LICENSE.txt", "ras-commander-rust-LICENSE.txt"):
        assert (FAST_HDF / "licenses" / name).is_file()


def test_notice_bundle_lists_the_audited_components():
    notices = (FAST_HDF / "THIRD-PARTY-NOTICES.md").read_text(encoding="utf-8")
    pin = tomllib.loads((FAST_HDF / "Cargo.toml").read_text())["dependencies"]["ras-commander-rust"]["rev"]
    assert "Generated by `scripts/generate_third_party_notices.py`" in notices
    for row in ("| zstd (C library, bundled by zstd-sys) |", "| approx |", "| prost |",
                "| prost-derive (compile time only) |", "| numpy |", "| earcutr |",
                "| ras-commander-rust |", "| hdf5-reader |", "| freestiler-core |"):
        assert row in notices, row
    assert "**none shipped**" not in notices
    engine_licence = (FAST_HDF / "licenses/ras-commander-rust-LICENSE.txt").read_text()
    assert "MIT License" in engine_licence and pin  # copy tracks the pinned engine
