"""Curated notebook contracts survive regeneration and agree across surfaces."""

import importlib.util
from pathlib import Path
import re

import pytest


ROOT = Path(__file__).resolve().parents[1]


def load_script(name):
    spec = importlib.util.spec_from_file_location(name, ROOT / ".claude/scripts" / f"{name}.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


generator = load_script("generate_examples_index")
metadata_generator = load_script("generate_notebooks_metadata")
validator = load_script("validate_notebooks_yml")


def test_curated_contracts_survive_metadata_refresh():
    metadata = generator.load_yml_meta(ROOT)
    assert metadata
    for name, entry in metadata.items():
        refreshed = metadata_generator.build_entry(ROOT / "examples" / entry["filename"], entry, {})
        for field in generator.FUNCTIONAL_FIELDS:
            assert (field in refreshed) == (field in entry), (name, field)
            if field in entry:
                assert refreshed[field] == entry[field], (name, field)


def test_human_and_json_catalog_share_curated_contracts():
    metadata = generator.load_yml_meta(ROOT)
    groups, count = generator.build_gallery(ROOT / "examples", ROOT, copy_thumbnails=False)
    records = {item["id"]: item for group in groups for item in group["notebooks"]}
    markdown, human_count, _ = generator.build_index_markdown(ROOT / "examples")
    assert human_count == count == len(records)
    assert count == len([entry for entry in metadata.values() if not entry.get("excluded")])
    for name, record in records.items():
        entry = metadata[name]
        assert entry["summary"].strip()
        assert entry["tags"]
        assert generator._table_text(entry["summary"]) in markdown
        for field in generator.FUNCTIONAL_FIELDS:
            assert (field in record) == (field in entry), (name, field)
            if field not in entry:
                continue
            assert record[field] == entry[field]
            values = entry[field] if isinstance(entry[field], list) else [entry[field]]
            assert all(generator._table_text(value) in markdown for value in values)
    assert "does not mean outputs are absent" in markdown
    assert "not a support badge" in markdown


