def test_capability_map_routes_to_existing_sources():
    page = ROOT / "docs/capabilities.md"
    text = page.read_text(encoding="utf-8")
    for target in re.findall(r"\]\(([^)]+)\)", text):
        path = target.split("#", 1)[0]
        if path.startswith("notebooks/"):
            source = ROOT / "examples" / Path(path).with_suffix(".ipynb").name
            assert source.is_file(), target
        elif path == "examples/index.json":
            continue  # Generated by the catalog build; may not exist in a clean checkout.
        else:
            assert (page.parent / path).is_file(), target
    assert "experimental" in text
    assert not re.search(r"\]\([^)]*notebooks/(223|311)_", text)


def test_function_inventory_distinguishes_code_from_prose_and_constants():
    notebook = {"cells": [{"cell_type": "code", "source": '''
# HdfMesh.get_mesh_perimeter("01")
print("RasProcess.exe and RasUsgsCore.get_discharge are prose")
names = {"ras.exe", "rasmapper.exe"}
limit = GeomCrossSection.MAX_XS_POINTS
GeomCrossSection.MAX_XS_POINTS()
directory = RasExamples.projects_dir
operations = {"function": RasMapperLayerCommandWorkflow.run_command}
callback = RasPlan.get_plan_path
RasPlan.update_plan_intervals("01", computation_interval="5MIN")
print(f"{RasPlan.get_shortid('01')}")
ras.project_path
HdfMesh.missing_reader("01")
'''}]}
    diagnostics = []
    assert metadata_generator.derive_functions(notebook, diagnostics) == [
        "GeomCrossSection.MAX_XS_POINTS", "HdfMesh.missing_reader",
        "RasMapperLayerCommandWorkflow.run_command",
        "RasPlan.get_plan_path", "RasPlan.get_shortid", "RasPlan.update_plan_intervals",
        "ras.project_path",
    ]
    assert diagnostics == []


