def test_manifest_exports_resolve_without_accepting_arbitrary_members():
    from ras_commander.api_surface import PUBLIC_MODULES

    assert {"ras_commander.geom", "ras_commander.hdf", "ras_commander.gui",
            "ras_commander.terrain"} <= set(PUBLIC_MODULES)
    index = validator.build_symbol_index()
    for symbol in ["GeomHtab.get_optimization_report", "HdfStruc1D.get_structure_max_values",
                   "RasMapperBankLineWorkflow.create_bank_lines_from_xs_bank_stations",
                   "RasTerrainMod.get_terrain_profile", "ras.project_path"]:
        assert validator.classify_symbol(symbol, *index) == "ok", symbol
    assert validator.classify_symbol("HdfMesh.missing_reader", *index) == "bad"
    assert validator.classify_symbol("GeomCrossSection.MAX_XS_POINTS", *index) == "bad"


def test_unavailable_approved_module_remains_explicit(monkeypatch):
    original_import = validator.importlib.import_module

    def import_without_gui(name):
        if name == "ras_commander.gui":
            raise ImportError("optional desktop dependency unavailable")
        return original_import(name)

    monkeypatch.setattr(validator.importlib, "import_module", import_without_gui)
    diagnostics = []
    index = validator.build_symbol_index(diagnostics)
    assert validator.classify_symbol(
        "RasMapperBankLineWorkflow.create_bank_lines_from_xs_bank_stations", *index
    ) == "unverifiable"
    assert any("ras_commander.gui unavailable" in message for message in diagnostics)


