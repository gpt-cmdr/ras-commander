"""PY-ROUTE-3 attribute fidelity on a synthetic h5py fixture (review P2-1, bitfields, P3-A).

The fixture is generated by h5py in ``tmp_path`` (never a real model) and puts
every attribute class on a group *and* on a dataset, so both engine readers
(``typed_group_attributes`` and ``typed_dataset_attributes``) are exercised:

- H5S_NULL dataspaces (h5py ``Empty``) of f4, i4, big-endian u8, fixed text and
  bitfield, next to the look-alikes they must not be confused with (zero-length
  simple arrays, scalars, one-element arrays);
- bitfields (B8 scalar and array, big-endian B16, little-endian 2-D B32), which
  h5py reads as unsigned integers of the same size and order;
- one variable-length string, which the engine does not type.

``fast_hdf.read_attrs``/``read_attr`` must return exactly ``obj.attrs[name]`` in
h5py, auto and required mode (type, dtype with byte order, shape, bytes, or
``Empty`` with the same dtype). Required mode refuses only what the engine cannot
reproduce (the vlen string) and attributes of a virtual dataset (P3-A).
"""
import h5py
import numpy as np
import pytest
from h5py import h5a, h5s, h5t

NAMES_TYPED = [
    "null f4", "null i4", "null u8 be", "null str", "null bitfield",
    "empty f4", "empty str", "scalar f4", "scalar str", "one f8",
    "bitfield b8 scalar", "bitfield b8 array", "bitfield b16 be", "bitfield b32 le 2d",
]
OWNERS = ["Attrs Group", "Attrs Dataset"]


def _null_attr(obj, name, tid):
    h5a.create(obj.id, name.encode(), tid, h5s.create(h5s.NULL)).close()


def _simple_attr(obj, name, tid, data):
    data = np.require(data, requirements="C")  # keeps 0-d (ascontiguousarray promotes to 1-d)
    space = h5s.create_simple(data.shape) if data.shape else h5s.create(h5s.SCALAR)
    attr = h5a.create(obj.id, name.encode(), tid, space)
    attr.write(data, mtype=tid)
    attr.close()


def _fixed_string(width):
    tid = h5t.C_S1.copy()
    tid.set_size(width)
    tid.set_strpad(h5t.STR_NULLPAD)
    return tid


def _populate(obj):
    _null_attr(obj, "null f4", h5t.IEEE_F32LE)
    _null_attr(obj, "null i4", h5t.STD_I32LE)
    _null_attr(obj, "null u8 be", h5t.STD_U64BE)
    _null_attr(obj, "null str", _fixed_string(8))
    _null_attr(obj, "null bitfield", h5t.STD_B8LE)
    obj.attrs["empty f4"] = np.array([], dtype="<f4")
    obj.attrs["empty str"] = np.array([], dtype="S4")
    obj.attrs["scalar f4"] = np.float32(1.5)
    obj.attrs["scalar str"] = np.bytes_(b"abc")
    obj.attrs["one f8"] = np.array([2.25], dtype="<f8")
    _simple_attr(obj, "bitfield b8 scalar", h5t.STD_B8LE, np.array(0xA5, dtype="u1"))
    _simple_attr(obj, "bitfield b8 array", h5t.STD_B8LE, np.arange(16, dtype="u1"))
    _simple_attr(obj, "bitfield b16 be", h5t.STD_B16BE, np.array([1, 258, 65535], dtype=">u2"))
    _simple_attr(obj, "bitfield b32 le 2d", h5t.STD_B32LE, np.arange(6, dtype="<u4").reshape(2, 3))


@pytest.fixture
def native():
    module = pytest.importorskip("ras_commander_fast_hdf")
    assert module.API_VERSION == 11
    return module


@pytest.fixture
def fixture_path(tmp_path):
    """Synthetic attribute fixture; ``with_vlen`` adds the one untyped attribute."""
    def make(with_vlen=False):
        path = tmp_path / ("attrs-vlen.h5" if with_vlen else "attrs.h5")
        with h5py.File(path, "w", libver="earliest") as f:
            group = f.create_group("Attrs Group")
            _populate(group)
            ds = f.create_dataset("Attrs Dataset", data=np.arange(4, dtype="<f4"))
            _populate(ds)
            if with_vlen:
                group.attrs["vlen str"] = "variable"
                ds.attrs["vlen str"] = "variable"
        return str(path)
    return make


def same(actual, expected):
    """h5py-exact: Python type, dtype (byte order included), shape and bytes, or Empty dtype."""
    assert type(actual) is type(expected), (type(actual), type(expected))
    if isinstance(expected, h5py.Empty):
        assert actual.dtype == expected.dtype and actual.dtype.str == expected.dtype.str
        return
    if isinstance(expected, (str, bytes)):
        assert actual == expected
        return
    a, e = np.asarray(actual), np.asarray(expected)
    assert a.dtype.str == e.dtype.str and a.shape == e.shape
    assert a.tobytes() == e.tobytes()


def _modes(monkeypatch):
    from ras_commander import fast_hdf
    for mode in ("0", "auto", "required"):
        monkeypatch.setenv("RAS_COMMANDER_FAST_HDF", mode)
        fast_hdf.close_sessions()
        yield mode


def test_fixture_is_what_h5py_reports(fixture_path):
    with h5py.File(fixture_path(), "r") as f:
        for owner in OWNERS:
            attrs = f[owner].attrs
            for name in [n for n in NAMES_TYPED if n.startswith("null")]:
                assert isinstance(attrs[name], h5py.Empty)
            assert attrs["empty f4"].shape == (0,) and attrs["empty str"].shape == (0,)
            assert attrs["bitfield b16 be"].dtype.str == ">u2"
            assert isinstance(attrs["bitfield b8 scalar"], np.uint8)


@pytest.mark.parametrize("owner", OWNERS)
def test_read_attrs_exact_in_every_mode(owner, native, fixture_path, monkeypatch):
    from ras_commander import fast_hdf
    path = fixture_path()
    with h5py.File(path, "r") as f:
        obj = f[owner]
        expected = {k: obj.attrs[k] for k in obj.attrs}
        assert sorted(expected) == sorted(NAMES_TYPED)
        for mode in _modes(monkeypatch):
            with fast_hdf.trace_reads() as trace:
                actual = fast_hdf.read_attrs(obj)
            assert list(actual) == list(expected)
            for name in expected:
                same(actual[name], expected[name])
            backends = {r["backend"] for r in trace}
            assert backends == ({"h5py"} if mode == "0" else {"native-typed"}), (mode, trace)


@pytest.mark.parametrize("owner", OWNERS)
@pytest.mark.parametrize("name", NAMES_TYPED)
def test_read_attr_exact_in_every_mode(owner, name, native, fixture_path, monkeypatch):
    from ras_commander import fast_hdf
    with h5py.File(fixture_path(), "r") as f:
        obj = f[owner]
        expected = obj.attrs[name]
        for mode in _modes(monkeypatch):
            with fast_hdf.trace_reads() as trace:
                same(fast_hdf.read_attr(obj, name), expected)
            assert [r["backend"] for r in trace] == ["h5py" if mode == "0" else "native-typed"]


def test_engine_reports_null_dataspace_explicitly(native, fixture_path):
    path = fixture_path()
    group = {a["name"]: a for a in native.typed_group_attributes(path, "/Attrs Group")}
    reported = native.typed_dataset_attributes(path, "Attrs Dataset")
    assert reported["capability"]["status"] == "supported"
    dataset = {a["name"]: a for a in reported["value"]}
    for attrs in (group, dataset):
        assert attrs["null f4"]["dataspace"] == "null" and attrs["null f4"]["raw_bytes"] == b""
        assert attrs["empty f4"]["dataspace"] == "simple" and attrs["empty f4"]["shape"] == [0]
        assert attrs["scalar f4"]["dataspace"] == "scalar" and attrs["scalar f4"]["shape"] == []
        bit = attrs["bitfield b16 be"]
        assert bit["attribute_type"] == {"kind": "bitfield", "bytes": 2, "byte_order": "big"}
        assert bit["value"] == np.array([1, 258, 65535], dtype=">u2").tobytes()


def test_absent_attribute_and_default(native, fixture_path, monkeypatch):
    from ras_commander import fast_hdf
    with h5py.File(fixture_path(), "r") as f:
        obj = f["Attrs Dataset"]
        with pytest.raises(KeyError) as h5py_error:
            obj.attrs["missing"]
        for _ in _modes(monkeypatch):
            assert fast_hdf.read_attr(obj, "missing", None) is None
            assert fast_hdf.read_attr(obj, "missing", b"x") == b"x"
            with pytest.raises(KeyError) as error:
                fast_hdf.read_attr(obj, "missing")
            assert str(error.value) == str(h5py_error.value)


@pytest.mark.parametrize("owner", OWNERS)
def test_untyped_vlen_attribute(owner, native, fixture_path, monkeypatch):
    """The engine has no vlen attribute type: auto is h5py-exact per attribute, required refuses.

    ``read_attr`` of a typed sibling stays native in required mode.
    """
    from ras_commander import fast_hdf
    with h5py.File(fixture_path(with_vlen=True), "r") as f:
        obj = f[owner]
        expected = {k: obj.attrs[k] for k in obj.attrs}
        monkeypatch.setenv("RAS_COMMANDER_FAST_HDF", "auto")
        with fast_hdf.trace_reads() as trace:
            actual = fast_hdf.read_attrs(obj)
        for name in expected:
            same(actual[name], expected[name])
        assert [r["backend"] for r in trace] == ["h5py-fallback"]
        same(fast_hdf.read_attr(obj, "vlen str"), expected["vlen str"])
        monkeypatch.setenv("RAS_COMMANDER_FAST_HDF", "required")
        with pytest.raises(fast_hdf.FastHdfError, match="vlen str"):
            fast_hdf.read_attrs(obj)
        with pytest.raises(fast_hdf.FastHdfError, match="vlen str"):
            fast_hdf.read_attr(obj, "vlen str")
        same(fast_hdf.read_attr(obj, "null f4"), expected["null f4"])


def test_virtual_dataset_attributes_refused_in_required_mode(native, fixture_path, tmp_path, monkeypatch):
    """Review P3-A: attributes of a virtual dataset are never served silently by h5py in required mode."""
    from ras_commander import fast_hdf
    source = fixture_path()
    path = tmp_path / "virtual.h5"
    with h5py.File(path, "w", libver="latest") as f:
        layout = h5py.VirtualLayout(shape=(4,), dtype="<f4")
        layout[:] = h5py.VirtualSource(source, "Attrs Dataset", shape=(4,))
        ds = f.create_virtual_dataset("Virtual", layout)
        ds.attrs["scale"] = np.float64(0.5)
        ds.attrs["units"] = np.bytes_(b"ft")
    with h5py.File(path, "r") as f:
        obj = f["Virtual"]
        assert obj.is_virtual
        expected = {k: obj.attrs[k] for k in obj.attrs}
        monkeypatch.setenv("RAS_COMMANDER_FAST_HDF", "auto")
        with fast_hdf.trace_reads() as trace:
            actual = fast_hdf.read_attrs(obj)
        for name in expected:
            same(actual[name], expected[name])
        assert [r["backend"] for r in trace] == ["h5py-fallback"]
        same(fast_hdf.read_attr(obj, "scale"), expected["scale"])
        monkeypatch.setenv("RAS_COMMANDER_FAST_HDF", "required")
        with pytest.raises(fast_hdf.FastHdfError, match="virtual/external"):
            fast_hdf.read_attrs(obj)
        with pytest.raises(fast_hdf.FastHdfError, match="virtual/external"):
            fast_hdf.read_attr(obj, "units")
