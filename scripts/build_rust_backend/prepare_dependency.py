"""Prepare the locally patched hdf5-reader dependency for the fast-hdf build.

The extension's Cargo.lock records ``hdf5-reader`` as a path override of
``gpt-cmdr/netcdf-rust`` at a pinned revision plus two reviewed fixes. This
script recreates that override in a caller-chosen local directory:

1. clone the dependency from ``--source`` (Git URL or local repository),
2. check out the pinned commit and verify its commit and tree hashes,
3. verify each checked-in patch against its recorded SHA256,
4. apply the patches and verify the resulting tree hash,
5. write ``<dest>.receipt.json`` with Cargo ``--config`` and TOML overrides.

Nothing is published or pushed; an existing destination is verified and
reused, never reset. Only Python's standard library and ``git`` are required.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
MANIFEST = HERE / "dependency.json"


class PrepareError(RuntimeError):
    """The dependency could not be prepared exactly as pinned."""


def sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def git(*args, cwd: Path | None = None, env: dict | None = None) -> str:
    command = ["git", "-c", "core.autocrlf=false", "-c", "core.safecrlf=false", *map(str, args)]
    result = subprocess.run(command, cwd=cwd, capture_output=True, text=True,
                            env=None if env is None else {**os.environ, **env})
    if result.returncode:
        raise PrepareError(f"git {' '.join(map(str, args))} failed: {result.stderr.strip()}")
    return result.stdout.strip()


def load_manifest(path: Path = MANIFEST) -> dict:
    manifest = json.loads(Path(path).read_text(encoding="utf-8"))
    for key in ("commit", "tree", "patches", "cargo_patch_source", "override_crates"):
        if key not in manifest:
            raise PrepareError(f"Dependency manifest lacks {key!r}")
    return manifest


def verify_patches(manifest: dict, base: Path = HERE) -> list[Path]:
    """Return patch paths after checking every recorded SHA256."""
    paths = []
    for entry in manifest["patches"]:
        path = (base / entry["file"]).resolve()
        if not path.is_file():
            raise PrepareError(f"Patch missing: {entry['file']}")
        actual = sha256_file(path)
        if actual != entry["sha256"]:
            raise PrepareError(f"Patch SHA256 mismatch for {entry['file']}: {actual}")
        paths.append(path)
    return paths


def worktree_tree(repo: Path) -> str:
    """Tree hash of the current working tree, using a scratch index (no commit)."""
    index = Path(git("rev-parse", "--absolute-git-dir", cwd=repo)) / "prepare-dependency.index"
    env = {"GIT_INDEX_FILE": str(index)}
    try:
        git("read-tree", "HEAD", cwd=repo, env=env)
        git("add", "-A", cwd=repo, env=env)
        return git("write-tree", cwd=repo, env=env)
    finally:
        index.unlink(missing_ok=True)


def cargo_config_args(dest: Path, manifest: dict) -> list[str]:
    source = manifest["cargo_patch_source"]
    args = []
    for crate in manifest["override_crates"]:
        crate_path = (dest / crate).resolve().as_posix()
        args += ["--config", f'patch."{source}".{crate}.path="{crate_path}"']
    return args


def cargo_patch_toml(dest: Path, manifest: dict) -> str:
    """Equivalent ``.cargo/config.toml`` [patch] table for tools lacking --config."""
    rows = [f'{crate} = {{ path = "{(dest / crate).resolve().as_posix()}" }}'
            for crate in manifest["override_crates"]]
    header = "# Local unpublished override generated by prepare_dependency.py"
    table = f'[patch."{manifest["cargo_patch_source"]}"]'
    return "\n".join([header, table, *rows]) + "\n"


def prepare(dest: Path, source: str | None = None, manifest_path: Path = MANIFEST) -> dict:
    manifest = load_manifest(manifest_path)
    patches = verify_patches(manifest, Path(manifest_path).resolve().parent)
    dest = Path(dest).expanduser().resolve()
    expected = manifest.get("patched_tree")
    if dest.exists():
        if not (dest / ".git").exists():
            raise PrepareError(f"{dest} exists and is not a prepared dependency; refusing to overwrite")
        head = git("rev-parse", "HEAD", cwd=dest)
        tree = worktree_tree(dest)
        if head != manifest["commit"] or (expected and tree != expected):
            raise PrepareError(
                f"Existing {dest} differs (HEAD {head}, tree {tree}); preserved, not reset")
        state = "existing-verified"
    else:
        dest.parent.mkdir(parents=True, exist_ok=True)
        git("clone", "--no-checkout", "--no-hardlinks", source or manifest["default_clone_source"], dest)
        git("checkout", "--detach", manifest["commit"], cwd=dest)
        if git("rev-parse", "HEAD", cwd=dest) != manifest["commit"]:
            raise PrepareError("Pinned commit was not checked out")
        if git("rev-parse", "HEAD^{tree}", cwd=dest) != manifest["tree"]:
            raise PrepareError("Pinned commit has an unexpected tree")
        if worktree_tree(dest) != manifest["tree"]:
            raise PrepareError("Checked-out working tree differs from the pinned tree")
        for patch in patches:
            git("apply", "--check", "--whitespace=nowarn", patch, cwd=dest)
            git("apply", "--whitespace=nowarn", patch, cwd=dest)
        tree = worktree_tree(dest)
        if expected and tree != expected:
            raise PrepareError(f"Patched tree {tree} differs from recorded {expected}")
        state = "created"
    licenses = {}
    for name in manifest.get("license_files", []):
        path = dest / name
        if not path.is_file():
            raise PrepareError(f"Dependency license file missing: {name}")
        licenses[name] = sha256_file(path)
    receipt = {
        "state": state,
        "dest": dest.as_posix(),
        "source": source or manifest["default_clone_source"],
        "commit": manifest["commit"],
        "base_tree": manifest["tree"],
        "patched_tree": tree,
        "patched_tree_recorded": expected,
        "patches": {Path(p).name: sha256_file(p) for p in patches},
        "license": manifest.get("license"),
        "license_files": licenses,
        "cargo_config_args": cargo_config_args(dest, manifest),
        "cargo_patch_toml": cargo_patch_toml(dest, manifest),
    }
    (dest.parent / f"{dest.name}.receipt.json").write_text(json.dumps(receipt, indent=2), encoding="utf-8")
    return receipt


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--dest", type=Path, required=True,
                        help="Local directory for the patched dependency (created if absent)")
    parser.add_argument("--source", help="Git URL or local repository containing the pinned commit")
    parser.add_argument("--manifest", type=Path, default=MANIFEST)
    args = parser.parse_args(argv)
    try:
        receipt = prepare(args.dest, args.source, args.manifest)
    except PrepareError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 1
    print(json.dumps(receipt, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
